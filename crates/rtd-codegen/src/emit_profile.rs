/// A projection or encoding failure. Every variant fails closed.
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum ProjectionError {
    /// The target profile is not enabled.
    UnsupportedProfile(i32),
    /// The value's constructor has no route in the target profile.
    Unrepresentable {
        /// Target layer.
        layer: i32,
        /// Constructor wire identifier.
        wire_id: u32,
    },
    /// The route requires per-route codecs not emitted in this build.
    RouteNotEmitted(Route),
}

impl std::fmt::Display for ProjectionError {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        match self {
            ProjectionError::UnsupportedProfile(layer) => {
                write!(f, "unsupported profile layer {layer}")
            }
            ProjectionError::Unrepresentable { layer, wire_id } => write!(
                f,
                "value {wire_id:#010x} is not representable in layer {layer}"
            ),
            ProjectionError::RouteNotEmitted(route) => {
                write!(f, "route {} is not emitted in this build", route.mode.as_str())
            }
        }
    }
}

impl std::error::Error for ProjectionError {}

/// A canonical value frozen once for per-profile encoding.
#[derive(Debug, Clone)]
pub struct FrozenObject {
    value: Object,
    type_id: u32,
}

impl FrozenObject {
    /// Freezes a canonical value, validating representability.
    ///
    /// # Errors
    ///
    /// Returns an error when the value's constructor is not part of the
    /// canonical route table.
    pub fn freeze(value: Object) -> Result<Self, ProjectionError> {
        let type_id = value.type_id();
        let representable = ROUTES
            .iter()
            .any(|route| route.profile == CANONICAL_LAYER && route.wire_id == type_id);
        if !representable {
            return Err(ProjectionError::Unrepresentable {
                layer: CANONICAL_LAYER,
                wire_id: type_id,
            });
        }
        Ok(Self { value, type_id })
    }

    /// Returns the canonical value.
    #[must_use]
    pub fn canonical(&self) -> &Object {
        &self.value
    }

    /// Returns the constructor wire identifier.
    #[must_use]
    pub const fn type_id(&self) -> u32 {
        self.type_id
    }

    /// Encodes the value for an exact profile, failing closed.
    ///
    /// # Errors
    ///
    /// Returns an error when the profile is unsupported or cannot represent the
    /// value; it never falls back to the canonical encoding.
    pub fn encode(&self, profile: Profile, out: &mut Writer) -> Result<(), ProjectionError> {
        let route = lookup_route(profile, self.type_id).ok_or(ProjectionError::Unrepresentable {
            layer: profile.layer,
            wire_id: self.type_id,
        })?;
        encode_route(route, &self.value, out)
    }
}

/// Encodes a canonical value according to an exact route.
///
/// # Errors
///
/// Returns an error for non-direct routes, which require per-route codecs.
pub fn encode_route(route: Route, value: &Object, out: &mut Writer) -> Result<(), ProjectionError> {
    match route.mode {
        RouteMode::Direct => {
            value.encode(out);
            Ok(())
        }
        _ => Err(ProjectionError::RouteNotEmitted(route)),
    }
}

/// Decodes a boxed object for an exact profile, failing closed.
///
/// # Errors
///
/// Returns an error when the profile is unsupported, a limit is exceeded,
/// trailing bytes remain, or the value has no route in the profile.
pub fn decode_object(
    profile: Profile,
    bytes: &[u8],
    limits: Limits,
) -> Result<Object, AdmitError> {
    if !profile.is_supported() {
        return Err(AdmitError::UnsupportedLayer(profile.layer));
    }
    if bytes.len() > limits.max_wire_bytes {
        return Err(AdmitError::Limit {
            name: "max_wire_bytes",
            value: bytes.len(),
        });
    }
    let mut decoder = Decoder::new(bytes, limits.decode_limits());
    let value = Object::decode(&mut decoder)?;
    if !decoder.is_empty() {
        return Err(AdmitError::Limit {
            name: "trailing_bytes",
            value: decoder.remaining(),
        });
    }
    let route = lookup_route(profile, value.type_id())
        .ok_or(AdmitError::UnsupportedTerminal(value.type_id()))?;
    if route.mode != RouteMode::Direct {
        return Err(AdmitError::UnsupportedRoute(route));
    }
    Ok(value)
}

/// A dispatch failure.
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum DispatchError {
    /// No handler is registered for the method.
    NoHandler(SemanticId),
    /// The handler rejected the call.
    Handler(String),
    /// The result could not be encoded for the effective profile.
    Projection(ProjectionError),
    /// A naked invariant terminal cannot produce a frozen profile value.
    Value(ProjectionError),
}

impl std::fmt::Display for DispatchError {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        match self {
            DispatchError::NoHandler(id) => write!(f, "no handler for semantic {:016x}", id.0),
            DispatchError::Handler(message) => write!(f, "handler error: {message}"),
            DispatchError::Projection(error) => write!(f, "projection error: {error}"),
            DispatchError::Value(error) => write!(f, "value error: {error}"),
        }
    }
}

impl std::error::Error for DispatchError {}

/// A semantic handler.
pub trait Handler {
    /// Handles an admitted request and returns a canonical result.
    ///
    /// # Errors
    ///
    /// Returns a message when the call cannot be served.
    fn handle(&self, admission: &Admission) -> Result<Object, String>;
}

impl<F> Handler for F
where
    F: Fn(&Admission) -> Result<Object, String>,
{
    fn handle(&self, admission: &Admission) -> Result<Object, String> {
        self(admission)
    }
}

/// The result of dispatching an admitted call, bound to its call identity.
#[derive(Debug, Clone)]
pub struct DispatchResult {
    identity: CallIdentity,
    value: FrozenObject,
}

impl DispatchResult {
    /// Returns the admitted call identity that produced this result.
    #[must_use]
    pub fn identity(&self) -> &CallIdentity {
        &self.identity
    }

    /// Returns the frozen canonical result value.
    #[must_use]
    pub fn value(&self) -> &FrozenObject {
        &self.value
    }

    /// Consumes the result, returning the frozen canonical value.
    #[must_use]
    pub fn into_value(self) -> FrozenObject {
        self.value
    }

    /// Encodes the result for an exact profile, failing closed.
    ///
    /// # Errors
    ///
    /// As [`FrozenObject::encode`].
    pub fn encode(&self, profile: Profile, out: &mut Writer) -> Result<(), ProjectionError> {
        self.value.encode(profile, out)
    }
}

/// A dispatcher keyed by stable semantic identity.
#[derive(Default)]
pub struct Dispatcher {
    handlers: std::collections::HashMap<u64, Box<dyn Handler>>,
}

impl Dispatcher {
    /// Creates an empty dispatcher.
    #[must_use]
    pub fn new() -> Self {
        Self::default()
    }

    /// Registers a handler, replacing any previous handler for the identity.
    pub fn register<H: Handler + 'static>(&mut self, semantic: SemanticId, handler: H) {
        self.handlers.insert(semantic.0, Box::new(handler));
    }

    /// Dispatches an admitted request and freezes the canonical result.
    ///
    /// # Errors
    ///
    /// Returns an error when no handler is registered, the handler fails, or
    /// the result cannot be frozen.
    pub fn dispatch(&self, admission: &Admission) -> Result<DispatchResult, DispatchError> {
        let handler = self
            .handlers
            .get(&admission.semantic.0)
            .ok_or(DispatchError::NoHandler(admission.semantic))?;
        let value = handler
            .handle(admission)
            .map_err(DispatchError::Handler)?;
        let value = FrozenObject::freeze(value).map_err(DispatchError::Value)?;
        Ok(DispatchResult {
            identity: admission.call_identity.clone(),
            value,
        })
    }
}

/// Returns the raw SHA-256 of `bytes`.
fn sha256(bytes: &[u8]) -> [u8; 32] {
    use sha2::{Digest, Sha256};
    let mut hasher = Sha256::new();
    hasher.update(bytes);
    let mut out = [0u8; 32];
    out.copy_from_slice(&hasher.finalize());
    out
}
