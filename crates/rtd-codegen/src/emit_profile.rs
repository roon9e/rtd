fn local_name(definition: &Definition) -> String {
    definition
        .key
        .qname
        .rsplit('.')
        .next()
        .unwrap_or(&definition.key.qname)
        .to_owned()
}

fn fresh_name(used: &mut BTreeSet<String>, mut name: String, seed: u64) -> String {
    if used.insert(name.clone()) {
        return name;
    }
    name = format!("{name}_{seed:016x}");
    used.insert(name.clone());
    name
}

/// Emits the `rtd-tlprofile` source.
///
/// # Errors
///
/// Returns a message when emission fails.
pub(crate) fn emit(
    universe: &Universe,
    plan: &ConversionPlan,
    table: &RouteTable,
    _plans: &PlanSet,
    config: &RtdConfig,
) -> Result<String, String> {
    let mut out = String::new();
    out.push_str("// @generated by rtd-codegen. Do not edit by hand.\n\n");
    out.push_str("//! Generated multi-layer routing and admission runtime.\n\n");
    out.push_str("use rtd_bin::Writer;\nuse rtd_tg::{DecodeLimits, Decoder, Method, Object};\n\n");

    let canonical = config.canonical_layer;
    let profiles = &table.profiles;
    out.push_str(&format!(
        "/// The canonical schema layer.\npub const CANONICAL_LAYER: i32 = {canonical};\n\n"
    ));
    out.push_str("/// The enabled profile layers, ascending.\n");
    out.push_str("pub static PROFILES: &[i32] = &[");
    out.push_str(
        &profiles
            .iter()
            .map(|layer| layer.to_string())
            .collect::<Vec<_>>()
            .join(", "),
    );
    out.push_str("];\n\n");

    emit_profile(&mut out);
    emit_semantic_id(&mut out);
    emit_semantic_constants(&mut out, universe);
    emit_route(&mut out);
    out.push_str("/// Routes accepted by the enabled profiles.\nstatic ROUTES: &[Route] = &[\n");
    for route in &table.routes {
        out.push_str(&format!(
            "    Route {{ profile: {}, wire_id: {:#010x}, semantic: SemanticId({:#018x}), mode: RouteMode::{} }},\n",
            route.layer,
            route.wire_id,
            route.semantic_id,
            route_mode_variant(route.mode)
        ));
    }
    out.push_str("];\n\n");
    emit_lookup(&mut out);
    emit_invariant(&mut out, universe, table);
    emit_wrappers(&mut out, universe)?;
    emit_runtime(&mut out);
    emit_profile_codec(&mut out, universe, plan, table)?;
    emit_tests(&mut out);
    Ok(out)
}

/// Emits the per-profile route codecs: a profile-aware encoder/decoder for every
/// canonical class, object constructor and method, plus the `Object` and `Method`
/// dispatchers. A container that is `Direct` or `Retag` in a profile writes or
/// reads the canonical body; a `Rewrite` container routes every nested class,
/// object and method through the profile dispatchers, so the whole nested graph is
/// re-identified for the layer.
fn emit_profile_codec(
    out: &mut String,
    universe: &Universe,
    plan: &ConversionPlan,
    table: &RouteTable,
) -> Result<(), String> {
    use crate::emit::{ident_for_qname, variant_ident};
    use crate::emit_tg::class_context;

    let canonical = universe.canonical();
    let (class_map, classes, bare_ids) = class_context(canonical);
    let object_constructors: Vec<&Definition> = canonical
        .definitions
        .iter()
        .filter(|definition| {
            definition.key.category == Category::Type && definition.result.qname == "Object"
        })
        .collect();
    let methods: Vec<&Definition> = canonical
        .definitions
        .iter()
        .filter(|definition| definition.key.category == Category::Function)
        .collect();

    let semantic = |definition: &Definition| -> Result<u64, String> {
        table
            .lookup(canonical.layer, definition.wire_id)
            .map(|route| route.semantic_id)
            .ok_or_else(|| format!("no canonical route for {:#010x}", definition.wire_id))
    };
    let ctx = CodecContext {
        universe,
        plan,
        classes: &classes,
        bare_ids: &bare_ids,
        semantic: &semantic,
    };

    let mut class_names: Vec<&String> = class_map.keys().collect();
    class_names.sort();
    for qname in class_names {
        let mut ctors: Vec<&Definition> = class_map[qname].clone();
        ctors.sort_by(|a, b| a.key.qname.cmp(&b.key.qname));
        let ident = ident_for_qname(qname);
        let type_local = qname.rsplit('.').next().unwrap_or(qname);
        let is_concrete = ctors.len() == 1 && {
            let ctor_local = ctors[0]
                .key
                .qname
                .rsplit('.')
                .next()
                .unwrap_or(&ctors[0].key.qname);
            type_local.eq_ignore_ascii_case(ctor_local)
        };
        if is_concrete {
            emit_struct_codec(out, &ctx, &ident, ctors[0])?;
        } else {
            let variants: Vec<(String, &Definition)> = ctors
                .iter()
                .map(|ctor| {
                    let local = ctor.key.qname.rsplit('.').next().unwrap_or(&ctor.key.qname);
                    (variant_ident(local), *ctor)
                })
                .collect();
            emit_enum_codec(out, &ctx, &ident, &variants)?;
        }
    }
    for definition in &object_constructors {
        let ident = ident_for_qname(&definition.key.qname);
        emit_struct_codec(out, &ctx, &ident, definition)?;
    }
    for definition in &methods {
        let ident = ident_for_qname(&definition.key.qname);
        emit_struct_codec(out, &ctx, &ident, definition)?;
    }

    emit_object_codec(out, &class_map, &object_constructors);
    emit_method_codec(out, &methods);
    Ok(())
}

/// Shared inputs for emitting one container's profile codec and policy bodies.
struct CodecContext<'a> {
    universe: &'a Universe,
    plan: &'a ConversionPlan,
    classes: &'a std::collections::BTreeSet<String>,
    bare_ids: &'a std::collections::BTreeMap<String, (String, u32)>,
    semantic: &'a dyn Fn(&Definition) -> Result<u64, String>,
}

/// Per-container parameters for emitting a policy encode function set.
struct PolicyEncodeSpec<'a> {
    value_type: &'a str,
    pattern: &'a str,
    refutable: bool,
    fn_base: &'a str,
}

/// Per-container parameters for emitting a policy decode function set.
struct PolicyDecodeSpec<'a> {
    value_type: &'a str,
    construct: &'a str,
    fn_base: &'a str,
}

/// A field-shaped adapter conversion: the canonical field type and the profile
/// field type differ and a hook maps between them.
struct FieldHook {
    /// Canonical field value to the profile field value.
    encode: &'static str,
    /// Profile field value to the canonical field value.
    decode: &'static str,
    /// The profile field's inner Rust type (written on encode, read on decode).
    profile_inner: crate::emit_tg::RustType,
}

/// One supported policy layer for a canonical constructor.
struct PolicyLayer<'a> {
    layer: i32,
    profile_def: &'a Definition,
    obligations: Vec<&'a crate::obligations::Obligation>,
    /// `profile field name` to `canonical field name`.
    mapping: std::collections::BTreeMap<String, String>,
    /// `canonical field name` to `profile field name`.
    reverse: std::collections::BTreeMap<String, String>,
    /// Canonical mandatory fields the profile cannot supply; rebuilt from a
    /// recorded type default on decode.
    canonical_defaults: std::collections::BTreeSet<String>,
    /// `canonical field name` to its field adapter conversion.
    field_hooks: std::collections::BTreeMap<String, FieldHook>,
}

/// Builds the field adapter conversions for a layer, or `None` when any
/// obligation needs a shape this generator cannot emit yet (result, presence,
/// discard, vector or projection hooks), so the layer stays fail-closed.
fn collect_field_hooks(
    obligations: &[&crate::obligations::Obligation],
    definition: &Definition,
    profile_def: &Definition,
    reverse: &std::collections::BTreeMap<String, String>,
    classes: &std::collections::BTreeSet<String>,
    bare_ids: &std::collections::BTreeMap<String, (String, u32)>,
) -> Option<std::collections::BTreeMap<String, FieldHook>> {
    use crate::model::FieldKind;

    let mut partial: std::collections::BTreeMap<
        String,
        (Option<&'static str>, Option<&'static str>),
    > = std::collections::BTreeMap::new();
    for obligation in obligations {
        let Some(resolution) = &obligation.resolution else {
            return None;
        };
        match resolution.action.as_str() {
            "drop" | "reject-if-present" | "default" => {}
            "adapter" => {
                let convert = rtd_layerhooks_registry::field_convert(&resolution.hook)?;
                let (canonical, encode, decode) = match obligation.direction {
                    "canonical-to-profile" => {
                        (obligation.field.clone(), Some(convert.encode), None)
                    }
                    "profile-to-canonical" => {
                        (obligation.other_field.clone(), None, Some(convert.decode))
                    }
                    _ => return None,
                };
                let slot = partial.entry(canonical).or_insert((None, None));
                if let Some(function) = encode {
                    if slot.0.is_some() {
                        return None;
                    }
                    slot.0 = Some(function);
                }
                if let Some(function) = decode {
                    if slot.1.is_some() {
                        return None;
                    }
                    slot.1 = Some(function);
                }
            }
            _ => return None,
        }
    }
    let mut hooks = std::collections::BTreeMap::new();
    for (canonical, (encode, decode)) in partial {
        // Both directions and aligned optionality are required, and the field
        // must be a plain value on both sides.
        let (Some(encode), Some(decode)) = (encode, decode) else {
            return None;
        };
        let field = definition
            .fields
            .iter()
            .find(|field| field.name == canonical)?;
        if field.kind != FieldKind::Value {
            return None;
        }
        let profile_name = reverse.get(&canonical)?;
        let profile_field = profile_def
            .fields
            .iter()
            .find(|field| &field.name == profile_name)?;
        if profile_field.kind != FieldKind::Value {
            return None;
        }
        let canonical_optional = field
            .condition
            .as_ref()
            .is_some_and(|condition| !condition.presence_only);
        let profile_optional = profile_field
            .condition
            .as_ref()
            .is_some_and(|condition| !condition.presence_only);
        if canonical_optional != profile_optional {
            return None;
        }
        let profile_inner =
            crate::emit_tg::field_rust_type(profile_field, classes, bare_ids).ok()?;
        hooks.insert(
            canonical,
            FieldHook {
                encode,
                decode,
                profile_inner,
            },
        );
    }
    Some(hooks)
}

/// Collects the layers with a mechanical policy body: field projection (`drop`),
/// presence rejection (`reject-if-present`), a recorded `default`, or a
/// field-shaped adapter conversion. Any layer needing another shape stays
/// fail-closed.
fn collect_policy_layers<'a>(
    universe: &'a Universe,
    plan: &'a ConversionPlan,
    classes: &std::collections::BTreeSet<String>,
    bare_ids: &std::collections::BTreeMap<String, (String, u32)>,
    definition: &Definition,
) -> Vec<PolicyLayer<'a>> {
    use crate::model::FieldKind;
    use crate::obligations::Availability;

    let mut layers = Vec::new();
    for layer in plan.profiles.keys().copied() {
        let Some(conv) = plan
            .profile(layer)
            .and_then(|profile| profile.family(&definition.key))
        else {
            continue;
        };
        if conv.availability != Availability::Present {
            continue;
        }
        // A layer with no body obligations has an identical body and is handled
        // by `direct`/`rewrite`; only a layer with at least one obligation can
        // carry a policy body.
        let obligations: Vec<&crate::obligations::Obligation> = conv.body_obligations();
        if obligations.is_empty() {
            continue;
        }
        let Some(profile_def) = universe
            .schemas
            .get(&layer)
            .and_then(|schema| schema.find_key(&definition.key))
        else {
            continue;
        };
        let mapping: std::collections::BTreeMap<String, String> = conv
            .fields
            .iter()
            .filter(|m| !m.canonical_name.is_empty())
            .map(|m| (m.profile_name.clone(), m.canonical_name.clone()))
            .collect();
        // Every profile value field and presence bit must have a canonical
        // source; a profile-only field would need a default value, so it stays
        // fail-closed.
        if !profile_def
            .fields
            .iter()
            .all(|field| field.kind == FieldKind::FlagsWord || mapping.contains_key(&field.name))
        {
            continue;
        }
        let reverse: std::collections::BTreeMap<String, String> = mapping
            .iter()
            .map(|(profile_name, canonical_name)| (canonical_name.clone(), profile_name.clone()))
            .collect();
        // Canonical mandatory fields the profile lacks are rebuilt from a
        // recorded type default (`profile-to-canonical` `default` obligations).
        let canonical_defaults: std::collections::BTreeSet<String> = obligations
            .iter()
            .filter(|obligation| {
                obligation
                    .resolution
                    .as_ref()
                    .map(|resolution| resolution.action.as_str())
                    == Some("default")
                    && obligation.direction == "profile-to-canonical"
            })
            .map(|obligation| obligation.other_field.clone())
            .collect();
        let Some(field_hooks) = collect_field_hooks(
            &obligations,
            definition,
            profile_def,
            &reverse,
            classes,
            bare_ids,
        ) else {
            continue;
        };
        // Every canonical field the layer dropped must be optional (or defaulted)
        // so the canonical value can be rebuilt; otherwise it stays fail-closed.
        let rebuildable = definition.fields.iter().all(|field| {
            reverse.contains_key(&field.name)
                || field.kind == FieldKind::FlagsWord
                || field.condition.is_some()
                || canonical_defaults.contains(&field.name)
        });
        if !rebuildable {
            continue;
        }
        layers.push(PolicyLayer {
            layer,
            profile_def,
            obligations,
            mapping,
            reverse,
            canonical_defaults,
            field_hooks,
        });
    }
    layers
}

/// Emits the body that writes a canonical value into one policy layer's shape.
fn emit_policy_layer_body(
    code: &mut crate::emit_tg::Code,
    definition: &Definition,
    types: &[crate::emit_tg::RustType],
    layer: &PolicyLayer<'_>,
) -> Result<(), String> {
    use crate::emit::field_ident;
    use crate::emit_tg::encode_value;
    use crate::model::FieldKind;

    for obligation in &layer.obligations {
        if obligation
            .resolution
            .as_ref()
            .map(|resolution| resolution.action.as_str())
            != Some("reject-if-present")
        {
            continue;
        }
        let field = definition
            .fields
            .iter()
            .find(|field| field.name == obligation.field)
            .ok_or_else(|| format!("policy: no canonical field {}", obligation.field))?;
        let binding = field_ident(&field.name);
        let reject = format!(
            "return Err(ProjectionError::Unrepresentable {{ layer: profile.layer, wire_id: {:#010x} }});",
            definition.wire_id
        );
        match &field.condition {
            Some(condition) if condition.presence_only => {
                code.line(&format!("if *{binding} {{ {reject} }}"));
            }
            Some(_) => code.line(&format!("if {binding}.is_some() {{ {reject} }}")),
            None => code.line(&reject),
        }
    }
    for profile_field in &layer.profile_def.fields {
        if profile_field.kind != FieldKind::FlagsWord {
            continue;
        }
        let word = &profile_field.name;
        let local = format!("__flags_{word}");
        code.line(&format!("let mut {local} = 0u32;"));
        for other in &layer.profile_def.fields {
            let Some(condition) = &other.condition else {
                continue;
            };
            if &condition.word != word {
                continue;
            }
            let Some(canonical) = layer.mapping.get(&other.name) else {
                continue;
            };
            let Some(field) = definition
                .fields
                .iter()
                .find(|field| &field.name == canonical)
            else {
                continue;
            };
            let binding = field_ident(canonical);
            match &field.condition {
                Some(c) if c.presence_only => code.line(&format!(
                    "if *{binding} {{ {local} |= 1u32 << {}; }}",
                    condition.bit
                )),
                Some(_) => code.line(&format!(
                    "if {binding}.is_some() {{ {local} |= 1u32 << {}; }}",
                    condition.bit
                )),
                None => code.line(&format!("{local} |= 1u32 << {};", condition.bit)),
            }
        }
        code.line(&format!("__w.put_u32({local});"));
    }
    for profile_field in &layer.profile_def.fields {
        if profile_field.kind == FieldKind::FlagsWord
            || profile_field
                .condition
                .as_ref()
                .is_some_and(|condition| condition.presence_only)
        {
            continue;
        }
        let canonical = layer
            .mapping
            .get(&profile_field.name)
            .ok_or_else(|| format!("policy: profile field {} has no source", profile_field.name))?;
        let ordinal = definition
            .fields
            .iter()
            .position(|field| &field.name == canonical)
            .ok_or_else(|| format!("policy: canonical field {canonical} missing"))?;
        let ty = &types[ordinal];
        let binding = field_ident(canonical);
        if let Some(hook) = layer.field_hooks.get(canonical) {
            // A field-shaped adapter converts the field's inner value; the
            // surrounding `Option` is preserved by the generated call site.
            let encode_fn = hook.encode;
            let profile_inner = &hook.profile_inner;
            match &profile_field.condition {
                None => {
                    code.line(&format!("let __converted = {encode_fn}({binding})?;"));
                    encode_value(code, profile_inner, "__converted", false, true);
                }
                Some(_) => {
                    code.open(&format!("if let Some(value) = {binding} {{"));
                    code.line(&format!("let __converted = {encode_fn}(value)?;"));
                    encode_value(code, profile_inner, "__converted", false, true);
                    code.close("}");
                }
            }
            continue;
        }
        let source_optional = definition.fields[ordinal]
            .condition
            .as_ref()
            .is_some_and(|condition| !condition.presence_only);
        match &profile_field.condition {
            None if source_optional => {
                // The profile field is mandatory but canonical may omit it; the
                // reviewed `default` substitutes the absent value.
                let default = default_expr(ty).ok_or_else(|| {
                    format!(
                        "policy: canonical field {canonical} has no scalar default for {}",
                        definition.key.as_string()
                    )
                })?;
                code.open(&format!("if let Some(value) = {binding} {{"));
                encode_value(code, ty, "value", true, true);
                code.close("} else {");
                encode_value(code, ty, &default, false, true);
                code.close("}");
            }
            None => encode_value(code, ty, &binding, true, true),
            Some(_) => {
                code.open(&format!("if let Some(value) = {binding} {{"));
                encode_value(code, ty, "value", true, true);
                code.close("}");
            }
        }
    }
    Ok(())
}

/// Whether encoding or decoding a value of `ty` recurses through the profile
/// dispatchers, and so references the enclosing function's `profile` parameter.
fn type_uses_profile(ty: &crate::emit_tg::RustType) -> bool {
    use crate::emit_tg::RustType;
    match ty {
        RustType::Class(_) | RustType::ClassBare(_, _) | RustType::Object | RustType::Method => {
            true
        }
        RustType::VectorBoxed(element) | RustType::VectorBare(element) => {
            type_uses_profile(element)
        }
        _ => false,
    }
}

/// Wraps a hook's unboxed conversion result back into the canonical field's
/// declared type (boxed for class/object/method fields).
fn wrap_canonical(ty: &crate::emit_tg::RustType, expr: &str) -> String {
    use crate::emit_tg::RustType;
    match ty {
        RustType::Class(_) | RustType::Object | RustType::Method => {
            format!("::std::boxed::Box::new({expr})")
        }
        _ => expr.to_owned(),
    }
}

/// The expression a class default substitutes for an absent scalar value, or
/// `None` when the type has no representable default (so the layer fails closed).
fn default_expr(ty: &crate::emit_tg::RustType) -> Option<String> {
    use crate::emit_tg::RustType;
    Some(match ty {
        RustType::U32 => "0u32".to_owned(),
        RustType::I32 => "0i32".to_owned(),
        RustType::I64 => "0i64".to_owned(),
        RustType::F64 => "0.0f64".to_owned(),
        RustType::Bool => "false".to_owned(),
        RustType::String => "::std::string::String::new()".to_owned(),
        RustType::Bytes => "::std::vec::Vec::new()".to_owned(),
        _ => return None,
    })
}

/// Emits the per-layer `encode_policy_*` functions for one constructor.
///
/// `pattern` is the value pattern (a struct path, or a `Class::Variant` path)
/// and `refutable` selects the `let ... else { unreachable!() };` form used for
/// enum variants. Only the canonical fields a layer actually reads are bound;
/// the rest are elided with `..` so no unused binding is generated.
fn emit_policy_encode_fns(
    out: &mut String,
    spec: &PolicyEncodeSpec<'_>,
    definition: &Definition,
    types: &[crate::emit_tg::RustType],
    layers: &[PolicyLayer<'_>],
) -> Result<(), String> {
    use crate::emit_tg::Code;
    use crate::model::FieldKind;
    let PolicyEncodeSpec {
        value_type,
        pattern,
        refutable,
        fn_base,
    } = *spec;
    for layer in layers {
        let uses_profile = layer.obligations.iter().any(|obligation| {
            obligation
                .resolution
                .as_ref()
                .map(|resolution| resolution.action.as_str())
                == Some("reject-if-present")
        });
        let writes_nested = layer.profile_def.fields.iter().any(|profile_field| {
            if profile_field.kind == FieldKind::FlagsWord
                || profile_field
                    .condition
                    .as_ref()
                    .is_some_and(|condition| condition.presence_only)
            {
                return false;
            }
            let Some(canonical) = layer.mapping.get(&profile_field.name) else {
                return false;
            };
            // A converted field writes the profile type, not the canonical one.
            if let Some(hook) = layer.field_hooks.get(canonical) {
                return type_uses_profile(&hook.profile_inner);
            }
            definition
                .fields
                .iter()
                .position(|field| &field.name == canonical)
                .is_some_and(|ordinal| type_uses_profile(&types[ordinal]))
        });
        let profile_param = if uses_profile || writes_nested {
            "profile"
        } else {
            "_profile"
        };
        let mut used: Vec<String> = layer
            .reverse
            .keys()
            .filter(|name| {
                definition
                    .fields
                    .iter()
                    .find(|field| &&field.name == name)
                    .is_some_and(|field| field.kind != FieldKind::FlagsWord)
            })
            .cloned()
            .collect();
        for obligation in &layer.obligations {
            if obligation
                .resolution
                .as_ref()
                .map(|resolution| resolution.action.as_str())
                == Some("reject-if-present")
                && !used.contains(&obligation.field)
            {
                used.push(obligation.field.clone());
            }
        }
        used.sort();
        let bindings: Vec<String> = used
            .iter()
            .map(|name| crate::emit::field_ident(name))
            .collect();
        let destructure = if definition.fields.is_empty() {
            pattern.to_owned()
        } else if bindings.is_empty() {
            format!("{pattern} {{ .. }}")
        } else {
            format!("{pattern} {{ {}, .. }}", bindings.join(", "))
        };
        let extract = if refutable {
            format!("let {destructure} = value else {{ unreachable!() }};")
        } else {
            format!("let {destructure} = value;")
        };
        let mut code = Code::new();
        code.open(&format!(
            "fn encode_policy_{fn_base}_{}({profile_param}: Profile, value: &{value_type}, __w: &mut Writer) -> Result<(), ProjectionError> {{",
            layer.layer
        ));
        code.line(&extract);
        emit_policy_layer_body(&mut code, definition, types, layer)?;
        code.line("Ok(())");
        code.close("}");
        out.push_str(&code.out);
        out.push('\n');
    }
    Ok(())
}

/// Emits the per-layer `decode_policy_*` functions for one constructor.
fn emit_policy_decode_fns(
    out: &mut String,
    spec: &PolicyDecodeSpec<'_>,
    definition: &Definition,
    types: &[crate::emit_tg::RustType],
    layers: &[PolicyLayer<'_>],
) -> Result<(), String> {
    use crate::emit::field_ident;
    use crate::emit_tg::{Code, decode_expr};
    use crate::model::FieldKind;
    let PolicyDecodeSpec {
        value_type: qualified,
        construct,
        fn_base,
    } = *spec;

    for layer in layers {
        let reads_nested = layer.profile_def.fields.iter().any(|profile_field| {
            if profile_field.kind == FieldKind::FlagsWord
                || profile_field
                    .condition
                    .as_ref()
                    .is_some_and(|condition| condition.presence_only)
            {
                return false;
            }
            let Some(canonical) = layer.mapping.get(&profile_field.name) else {
                return false;
            };
            // A converted field reads the profile type, not the canonical one.
            if let Some(hook) = layer.field_hooks.get(canonical) {
                return type_uses_profile(&hook.profile_inner);
            }
            definition
                .fields
                .iter()
                .position(|field| &field.name == canonical)
                .is_some_and(|ordinal| type_uses_profile(&types[ordinal]))
        });
        let profile_param = if reads_nested { "profile" } else { "_profile" };
        let mut code = Code::new();
        code.open(&format!(
            "fn decode_policy_{fn_base}_{}({profile_param}: Profile, __d: &mut Decoder<'_>) -> Result<{qualified}, AdmitError> {{",
            layer.layer
        ));
        for profile_field in &layer.profile_def.fields {
            let binding = field_ident(&profile_field.name);
            if profile_field.kind == FieldKind::FlagsWord {
                let referenced = layer.profile_def.fields.iter().any(|other| {
                    other
                        .condition
                        .as_ref()
                        .is_some_and(|condition| condition.word == profile_field.name)
                });
                if referenced {
                    code.line(&format!("let {binding} = __d.take_u32()?;"));
                } else {
                    code.line("let _ = __d.take_u32()?;");
                }
                continue;
            }
            let canonical = layer.mapping.get(&profile_field.name).ok_or_else(|| {
                format!("policy: profile field {} has no source", profile_field.name)
            })?;
            let ordinal = definition
                .fields
                .iter()
                .position(|field| &field.name == canonical)
                .ok_or_else(|| format!("policy: canonical field {canonical} missing"))?;
            // The wire carries the profile type; only a converted field's inner
            // type differs from the canonical one.
            let read_ty = layer
                .field_hooks
                .get(canonical)
                .map_or(&types[ordinal], |hook| &hook.profile_inner);
            match &profile_field.condition {
                None => code.line(&format!(
                    "let {binding}: {} = {};",
                    read_ty.rendered_in(true),
                    decode_expr(read_ty, true)
                )),
                Some(condition) if condition.presence_only => code.line(&format!(
                    "let {binding}: bool = {} & (1u32 << {}) != 0;",
                    field_ident(&condition.word),
                    condition.bit
                )),
                Some(condition) => code.line(&format!(
                    "let {binding}: Option<{}> = if {} & (1u32 << {}) != 0 {{ Some({}) }} else {{ None }};",
                    read_ty.rendered_in(true),
                    field_ident(&condition.word),
                    condition.bit,
                    decode_expr(read_ty, true)
                )),
            }
        }
        // Convert field-shaped adapter fields from the profile type to canonical;
        // the shadowed binding keeps the same name for the rebuild below.
        for (canonical, hook) in &layer.field_hooks {
            let profile_name = layer
                .reverse
                .get(canonical)
                .ok_or_else(|| format!("policy: no profile field for {canonical}"))?;
            let binding = field_ident(profile_name);
            let ordinal = definition
                .fields
                .iter()
                .position(|field| &field.name == canonical)
                .ok_or_else(|| format!("policy: canonical field {canonical} missing"))?;
            let canonical_ty = types[ordinal].rendered_in(true);
            let decode_fn = hook.decode;
            let optional = definition.fields[ordinal]
                .condition
                .as_ref()
                .is_some_and(|condition| !condition.presence_only);
            if optional {
                let converted = wrap_canonical(&types[ordinal], &format!("{decode_fn}(&value)?"));
                code.line(&format!(
                    "let {binding}: Option<{canonical_ty}> = match {binding} {{ Some(value) => Some({converted}), None => None }};"
                ));
            } else {
                let converted =
                    wrap_canonical(&types[ordinal], &format!("{decode_fn}(&{binding})?"));
                code.line(&format!("let {binding}: {canonical_ty} = {converted};"));
            }
        }
        let mut fields = Vec::new();
        for (index, field) in definition.fields.iter().enumerate() {
            let name = field_ident(&field.name);
            if field.kind == FieldKind::FlagsWord {
                // Recompute the canonical flags word from the reconstructed
                // value so the layer's own bit layout never leaks into the
                // canonical value; dropped fields leave their bit clear.
                // The bit comes from the canonical field's condition; the
                // presence test from the reconstructed profile field's shape.
                let mut sets: Vec<(String, Option<bool>, u8)> = Vec::new();
                for other in &definition.fields {
                    let Some(condition) = &other.condition else {
                        continue;
                    };
                    if condition.word != field.name {
                        continue;
                    }
                    let Some(profile_name) = layer.reverse.get(&other.name) else {
                        continue;
                    };
                    let shape = layer
                        .profile_def
                        .fields
                        .iter()
                        .find(|profile| &profile.name == profile_name)
                        .and_then(|profile| profile.condition.as_ref())
                        .map(|condition| condition.presence_only);
                    sets.push((field_ident(profile_name), shape, condition.bit));
                }
                if sets.is_empty() {
                    code.line(&format!("let {name} = 0u32;"));
                } else {
                    code.line(&format!("let mut {name} = 0u32;"));
                    for (binding, shape, bit) in sets {
                        let set = format!("{name} |= 1u32 << {bit};");
                        match shape {
                            None => code.line(&set),
                            Some(true) => code.line(&format!("if {binding} {{ {set} }}")),
                            Some(false) => {
                                code.line(&format!("if {binding}.is_some() {{ {set} }}"));
                            }
                        }
                    }
                }
                fields.push(name);
                continue;
            }
            let ty = &types[index];
            let canonical_optional = field
                .condition
                .as_ref()
                .is_some_and(|condition| !condition.presence_only);
            if let Some(profile_name) = layer.reverse.get(&field.name) {
                let binding = field_ident(profile_name);
                let profile_mandatory = layer
                    .profile_def
                    .fields
                    .iter()
                    .find(|profile| &profile.name == profile_name)
                    .is_some_and(|profile| profile.condition.is_none());
                // A canonical optional field fed by a mandatory profile field is
                // always present after the `default` substitution.
                let expr = if canonical_optional && profile_mandatory {
                    format!("Some({binding})")
                } else {
                    binding
                };
                if expr == name {
                    fields.push(name);
                } else {
                    fields.push(format!("{name}: {expr}"));
                }
                continue;
            }
            if layer.canonical_defaults.contains(&field.name) {
                let default = default_expr(ty).ok_or_else(|| {
                    format!(
                        "policy: canonical field {} has no scalar default for {}",
                        field.name,
                        definition.key.as_string()
                    )
                })?;
                fields.push(format!("{name}: {default}"));
                continue;
            }
            let fallback = match &field.condition {
                Some(condition) if condition.presence_only => "false".to_owned(),
                _ => "None".to_owned(),
            };
            fields.push(format!("{name}: {fallback}"));
        }
        if fields.is_empty() {
            code.line(&format!("Ok({construct})"));
        } else {
            code.line(&format!("Ok({construct} {{ {} }})", fields.join(", ")));
        }
        code.close("}");
        out.push_str(&code.out);
        out.push('\n');
    }
    Ok(())
}

/// Emits the profile codec for a single-constructor (struct) container.
fn emit_struct_codec(
    out: &mut String,
    ctx: &CodecContext<'_>,
    ident: &str,
    definition: &Definition,
) -> Result<(), String> {
    use crate::emit::field_ident;
    use crate::emit_tg::{Code, emit_constructor_decode, emit_encode_fields, prepare};

    let types = prepare(definition, ctx.classes, ctx.bare_ids).map_err(|error| error.0)?;
    let sid = (ctx.semantic)(definition)?;
    let cid = definition.wire_id;
    let bindings: Vec<String> = definition
        .fields
        .iter()
        .map(|field| field_ident(&field.name))
        .collect();
    let has_fields = !definition.fields.is_empty();
    let qualified = format!("rtd_tg::{ident}");
    let fn_name = crate::emit::to_snake_case(ident);
    let value_param = if has_fields { "value" } else { "_value" };
    let layers = collect_policy_layers(
        ctx.universe,
        ctx.plan,
        ctx.classes,
        ctx.bare_ids,
        definition,
    );

    let mut code = Code::new();
    code.open(&format!(
        "pub fn encode_{fn_name}_profile(profile: Profile, {value_param}: &{qualified}, __w: &mut Writer) -> Result<(), ProjectionError> {{"
    ));
    code.line(&format!(
        "let route = lookup_route_semantic(profile, SemanticId({sid:#018x})).ok_or(ProjectionError::Unrepresentable {{ layer: profile.layer, wire_id: {cid:#010x} }})?;"
    ));
    code.open("match route.mode {");
    code.open("RouteMode::Direct | RouteMode::Retag => {");
    code.line("__w.put_u32(route.wire_id);");
    if has_fields {
        code.line(&format!(
            "let {qualified} {{ {} }} = value;",
            bindings.join(", ")
        ));
        emit_encode_fields(&mut code, &definition.fields, &types, false, false);
    }
    code.line("Ok(())");
    code.close("}");
    code.open("RouteMode::Rewrite => {");
    code.line("__w.put_u32(route.wire_id);");
    if has_fields {
        code.line(&format!(
            "let {qualified} {{ {} }} = value;",
            bindings.join(", ")
        ));
        emit_encode_fields(&mut code, &definition.fields, &types, false, true);
    }
    code.line("Ok(())");
    code.close("}");
    if !layers.is_empty() {
        code.open("RouteMode::Policy => {");
        code.line("__w.put_u32(route.wire_id);");
        code.open("match profile.layer {");
        for layer in &layers {
            code.line(&format!(
                "{} => encode_policy_{fn_name}_{}(profile, value, __w)?,",
                layer.layer, layer.layer
            ));
        }
        code.line("_ => return Err(ProjectionError::RouteNotEmitted(route)),");
        code.close("}");
        code.line("Ok(())");
        code.close("}");
    }
    code.open("_ => {");
    code.line("Err(ProjectionError::RouteNotEmitted(route))");
    code.close("}");
    code.close("}");
    code.close("}");
    out.push_str(&code.out);
    out.push('\n');
    emit_policy_encode_fns(
        out,
        &PolicyEncodeSpec {
            value_type: &qualified,
            pattern: &qualified,
            refutable: false,
            fn_base: &fn_name,
        },
        definition,
        &types,
        &layers,
    )?;

    let mut code = Code::new();
    code.open(&format!(
        "pub fn decode_{fn_name}_profile(profile: Profile, id: u32, __d: &mut Decoder<'_>) -> Result<{qualified}, AdmitError> {{"
    ));
    code.line("let route = lookup_route(profile, id).ok_or(AdmitError::Decode(::rtd_bin::Error::UnexpectedId { id, expected: 0 }))?;");
    code.open("match route.mode {");
    code.open("RouteMode::Direct | RouteMode::Retag => {");
    code.line(&format!(
        "Ok({qualified}::decode_with_id(__d, canonical_wire_id(route.semantic).unwrap_or(id))?)"
    ));
    code.close("}");
    code.open("RouteMode::Rewrite => {");
    emit_constructor_decode(&mut code, &definition.fields, &types, &qualified, true);
    code.close("}");
    if !layers.is_empty() {
        code.open("RouteMode::Policy => {");
        code.open("match profile.layer {");
        for layer in &layers {
            code.line(&format!(
                "{} => decode_policy_{fn_name}_{}(profile, __d),",
                layer.layer, layer.layer
            ));
        }
        code.line("_ => Err(AdmitError::UnsupportedRoute(route)),");
        code.close("}");
        code.close("}");
    }
    code.open("_ => {");
    code.line("Err(AdmitError::UnsupportedRoute(route))");
    code.close("}");
    code.close("}");
    code.close("}");
    out.push_str(&code.out);
    out.push('\n');
    emit_policy_decode_fns(
        out,
        &PolicyDecodeSpec {
            value_type: &qualified,
            construct: &qualified,
            fn_base: &fn_name,
        },
        definition,
        &types,
        &layers,
    )?;
    Ok(())
}

/// Emits the profile codec for a multi-constructor (enum) container.
fn emit_enum_codec(
    out: &mut String,
    ctx: &CodecContext<'_>,
    ident: &str,
    variants: &[(String, &Definition)],
) -> Result<(), String> {
    use crate::emit::field_ident;
    use crate::emit_tg::{Code, emit_constructor_decode, emit_encode_fields, prepare};

    let mut prepared = Vec::new();
    let mut variant_layers = Vec::new();
    for (variant, ctor) in variants {
        let types = prepare(ctor, ctx.classes, ctx.bare_ids).map_err(|error| error.0)?;
        let sid = (ctx.semantic)(ctor)?;
        let bindings: Vec<String> = ctor.fields.iter().map(|f| field_ident(&f.name)).collect();
        variant_layers.push(collect_policy_layers(
            ctx.universe,
            ctx.plan,
            ctx.classes,
            ctx.bare_ids,
            ctor,
        ));
        prepared.push((variant.clone(), *ctor, types, sid, bindings));
    }
    let has_policy = variant_layers.iter().any(|layers| !layers.is_empty());

    let qualified = format!("rtd_tg::{ident}");
    let fn_name = crate::emit::to_snake_case(ident);
    let mut code = Code::new();
    // The value parameter is named `__value`: a variant field may be called
    // `value`, and the match arm binds it for the whole arm body, which would
    // otherwise shadow the enum used by the policy dispatch.
    code.open(&format!(
        "pub fn encode_{fn_name}_profile(profile: Profile, __value: &{qualified}, __w: &mut Writer) -> Result<(), ProjectionError> {{"
    ));
    code.open("match __value {");
    for ((variant, ctor, types, sid, bindings), layers) in prepared.iter().zip(&variant_layers) {
        let cid = ctor.wire_id;
        if ctor.fields.is_empty() {
            code.open(&format!("{qualified}::{variant} => {{"));
        } else {
            code.open(&format!(
                "{qualified}::{variant} {{ {} }} => {{",
                bindings.join(", ")
            ));
        }
        code.line(&format!(
            "let route = lookup_route_semantic(profile, SemanticId({sid:#018x})).ok_or(ProjectionError::Unrepresentable {{ layer: profile.layer, wire_id: {cid:#010x} }})?;"
        ));
        code.open("match route.mode {");
        code.open("RouteMode::Direct | RouteMode::Retag => {");
        code.line("__w.put_u32(route.wire_id);");
        if !ctor.fields.is_empty() {
            emit_encode_fields(&mut code, &ctor.fields, types, false, false);
        }
        code.line("Ok(())");
        code.close("}");
        code.open("RouteMode::Rewrite => {");
        code.line("__w.put_u32(route.wire_id);");
        if !ctor.fields.is_empty() {
            emit_encode_fields(&mut code, &ctor.fields, types, false, true);
        }
        code.line("Ok(())");
        code.close("}");
        if !layers.is_empty() {
            let fn_base = variant_fn_base(&fn_name, variant);
            code.open("RouteMode::Policy => {");
            code.line("__w.put_u32(route.wire_id);");
            code.open("match profile.layer {");
            for layer in layers {
                code.line(&format!(
                    "{} => encode_policy_{fn_base}_{}(profile, __value, __w)?,",
                    layer.layer, layer.layer
                ));
            }
            code.line("_ => return Err(ProjectionError::RouteNotEmitted(route)),");
            code.close("}");
            code.line("Ok(())");
            code.close("}");
        }
        code.open("_ => {");
        code.line("Err(ProjectionError::RouteNotEmitted(route))");
        code.close("}");
        code.close("}");
        code.close("}");
    }
    code.close("}");
    code.close("}");
    out.push_str(&code.out);
    out.push('\n');
    let refutable = prepared.len() > 1;
    for ((variant, ctor, types, _sid, _bindings), layers) in prepared.iter().zip(&variant_layers) {
        if layers.is_empty() {
            continue;
        }
        let fn_base = variant_fn_base(&fn_name, variant);
        let construct = format!("{qualified}::{variant}");
        emit_policy_encode_fns(
            out,
            &PolicyEncodeSpec {
                value_type: &qualified,
                pattern: &construct,
                refutable,
                fn_base: &fn_base,
            },
            ctor,
            types,
            layers,
        )?;
    }

    let mut code = Code::new();
    code.open(&format!(
        "pub fn decode_{fn_name}_profile(profile: Profile, id: u32, __d: &mut Decoder<'_>) -> Result<{qualified}, AdmitError> {{"
    ));
    code.line("let route = lookup_route(profile, id).ok_or(AdmitError::Decode(::rtd_bin::Error::UnexpectedId { id, expected: 0 }))?;");
    code.open("match route.mode {");
    code.open("RouteMode::Direct | RouteMode::Retag => {");
    code.line(&format!(
        "Ok({qualified}::decode_with_id(__d, canonical_wire_id(route.semantic).unwrap_or(id))?)"
    ));
    code.close("}");
    code.open("RouteMode::Rewrite => {");
    code.open("match route.semantic.0 {");
    for (variant, ctor, types, sid, _bindings) in &prepared {
        code.open(&format!("{sid:#018x} => {{"));
        emit_constructor_decode(
            &mut code,
            &ctor.fields,
            types,
            &format!("{qualified}::{variant}"),
            true,
        );
        code.close("}");
    }
    code.line("_ => Err(AdmitError::UnsupportedRoute(route)),");
    code.close("}");
    code.close("}");
    if has_policy {
        code.open("RouteMode::Policy => {");
        code.open("match route.semantic.0 {");
        for ((variant, _ctor, _types, sid, _bindings), layers) in
            prepared.iter().zip(&variant_layers)
        {
            if layers.is_empty() {
                continue;
            }
            let fn_base = variant_fn_base(&fn_name, variant);
            code.open(&format!("{sid:#018x} => {{"));
            code.open("match profile.layer {");
            for layer in layers {
                code.line(&format!(
                    "{} => decode_policy_{fn_base}_{}(profile, __d),",
                    layer.layer, layer.layer
                ));
            }
            code.line("_ => Err(AdmitError::UnsupportedRoute(route)),");
            code.close("}");
            code.close("}");
        }
        code.line("_ => Err(AdmitError::UnsupportedRoute(route)),");
        code.close("}");
        code.close("}");
    }
    code.open("_ => {");
    code.line("Err(AdmitError::UnsupportedRoute(route))");
    code.close("}");
    code.close("}");
    code.close("}");
    out.push_str(&code.out);
    out.push('\n');
    for ((variant, ctor, types, _sid, _bindings), layers) in prepared.iter().zip(&variant_layers) {
        if layers.is_empty() {
            continue;
        }
        let fn_base = variant_fn_base(&fn_name, variant);
        let construct = format!("{qualified}::{variant}");
        emit_policy_decode_fns(
            out,
            &PolicyDecodeSpec {
                value_type: &qualified,
                construct: &construct,
                fn_base: &fn_base,
            },
            ctor,
            types,
            layers,
        )?;
    }
    Ok(())
}

/// Builds the policy codec base name for an enum variant: the container's
/// snake-case name plus the variant's, so per-variant bodies never collide.
fn variant_fn_base(fn_name: &str, variant: &str) -> String {
    format!("{fn_name}_{}", crate::emit::to_snake_case(variant))
}

/// Emits the `Object` profile dispatchers.
fn emit_object_codec(
    out: &mut String,
    class_map: &std::collections::BTreeMap<String, Vec<&Definition>>,
    object_constructors: &[&Definition],
) {
    use crate::emit::ident_for_qname;
    use crate::emit_tg::Code;

    let mut entries: Vec<(String, String)> = Vec::new();
    for qname in class_map.keys() {
        let ident = ident_for_qname(qname);
        entries.push((ident.clone(), ident));
    }
    for definition in object_constructors {
        let ident = ident_for_qname(&definition.key.qname);
        entries.push((ident.clone(), ident));
    }
    entries.sort();
    entries.dedup();

    let mut code = Code::new();
    code.open("pub fn encode_object_profile(profile: Profile, value: &Object, __w: &mut Writer) -> Result<(), ProjectionError> {");
    code.open("match value {");
    for (variant, fn_ident) in &entries {
        let fn_name = crate::emit::to_snake_case(fn_ident);
        code.line(&format!(
            "Object::{variant}(value) => encode_{fn_name}_profile(profile, value, __w),"
        ));
    }
    code.close("}");
    code.close("}");
    out.push_str(&code.out);
    out.push('\n');

    let mut by_id: Vec<(u32, String, String)> = Vec::new();
    for (qname, ctors) in class_map {
        let ident = ident_for_qname(qname);
        for ctor in ctors {
            by_id.push((ctor.wire_id, ident.clone(), ident.clone()));
        }
    }
    for definition in object_constructors {
        let ident = ident_for_qname(&definition.key.qname);
        by_id.push((definition.wire_id, ident.clone(), ident));
    }
    by_id.sort();
    by_id.dedup();
    let mut code = Code::new();
    code.open("pub fn decode_object_profile(profile: Profile, __d: &mut Decoder<'_>) -> Result<Object, AdmitError> {");
    code.line("let id = __d.take_u32()?;");
    code.line("let route = lookup_route(profile, id).ok_or(AdmitError::Decode(::rtd_bin::Error::UnexpectedId { id, expected: 0 }))?;");
    code.line("let canonical = canonical_wire_id(route.semantic).ok_or(AdmitError::UnsupportedRoute(route))?;");
    code.open("match canonical {");
    for (cid, variant, fn_ident) in &by_id {
        let fn_name = crate::emit::to_snake_case(fn_ident);
        code.line(&format!(
            "{cid:#010x} => Ok(Object::{variant}(::std::boxed::Box::new(decode_{fn_name}_profile(profile, id, __d)?))),"
        ));
    }
    code.line("_ => Err(AdmitError::UnsupportedRoute(route)),");
    code.close("}");
    code.close("}");
    out.push_str(&code.out);
    out.push('\n');
}

/// Emits the `Method` profile dispatchers.
fn emit_method_codec(out: &mut String, methods: &[&Definition]) {
    use crate::emit::ident_for_qname;
    use crate::emit_tg::Code;

    let mut entries: Vec<(String, String)> = methods
        .iter()
        .map(|definition| {
            let ident = ident_for_qname(&definition.key.qname);
            (ident.clone(), ident)
        })
        .collect();
    entries.sort();
    entries.dedup();

    let mut code = Code::new();
    code.open("pub fn encode_method_profile(profile: Profile, value: &Method, __w: &mut Writer) -> Result<(), ProjectionError> {");
    code.open("match value {");
    for (variant, fn_ident) in &entries {
        let fn_name = crate::emit::to_snake_case(fn_ident);
        code.line(&format!(
            "Method::{variant}(value) => encode_{fn_name}_profile(profile, value, __w),"
        ));
    }
    code.close("}");
    code.close("}");
    out.push_str(&code.out);
    out.push('\n');

    let mut by_id: Vec<(u32, String, String)> = methods
        .iter()
        .map(|definition| {
            let ident = ident_for_qname(&definition.key.qname);
            (definition.wire_id, ident.clone(), ident)
        })
        .collect();
    by_id.sort();
    by_id.dedup();
    let mut code = Code::new();
    code.open("pub fn decode_method_profile(profile: Profile, __d: &mut Decoder<'_>) -> Result<Method, AdmitError> {");
    code.line("let id = __d.take_u32()?;");
    code.line("let route = lookup_route(profile, id).ok_or(AdmitError::Decode(::rtd_bin::Error::UnexpectedId { id, expected: 0 }))?;");
    code.line("let canonical = canonical_wire_id(route.semantic).ok_or(AdmitError::UnsupportedRoute(route))?;");
    code.open("match canonical {");
    for (cid, variant, fn_ident) in &by_id {
        let fn_name = crate::emit::to_snake_case(fn_ident);
        code.line(&format!(
            "{cid:#010x} => Ok(Method::{variant}(::std::boxed::Box::new(decode_{fn_name}_profile(profile, id, __d)?))),"
        ));
    }
    code.line("_ => Err(AdmitError::UnsupportedRoute(route)),");
    code.close("}");
    code.close("}");
    out.push_str(&code.out);
    out.push('\n');
}

