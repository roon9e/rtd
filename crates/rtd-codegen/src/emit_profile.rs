/// An admission failure. Every variant fails closed.
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum AdmitError {
    /// The wire bytes could not be decoded.
    Decode(rtd_bin::Error),
    /// The selected layer is not enabled.
    UnsupportedLayer(i32),
    /// Two layer selectors disagreed.
    Conflict(i32, i32),
    /// A naked terminal is not wire-invariant.
    RequiresProfile(u32),
    /// The terminal has no route in the selected profile.
    UnsupportedTerminal(u32),
    /// The route exists but requires per-route codecs not emitted in this build.
    UnsupportedRoute(Route),
    /// A declared admission limit was exceeded.
    Limit {
        /// Limit name.
        name: &'static str,
        /// Measured value.
        value: usize,
    },
    /// A layer conversion hook refused the value.
    Hook(::rtd_layerhooks::HookError),
}

impl std::fmt::Display for AdmitError {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        match self {
            AdmitError::Decode(error) => write!(f, "decode error: {error}"),
            AdmitError::UnsupportedLayer(layer) => write!(f, "unsupported layer {layer}"),
            AdmitError::Conflict(a, b) => write!(f, "conflicting layer selectors {a} and {b}"),
            AdmitError::RequiresProfile(id) => {
                write!(f, "terminal {id:#010x} requires an exact profile")
            }
            AdmitError::UnsupportedTerminal(id) => {
                write!(f, "terminal {id:#010x} has no route in the selected profile")
            }
            AdmitError::UnsupportedRoute(route) => {
                write!(f, "route {} is not emitted in this build", route.mode.as_str())
            }
            AdmitError::Limit { name, value } => {
                write!(f, "admission limit {name} exceeded ({value})")
            }
            AdmitError::Hook(error) => write!(f, "layer conversion failed: {error}"),
        }
    }
}

impl std::error::Error for AdmitError {}

