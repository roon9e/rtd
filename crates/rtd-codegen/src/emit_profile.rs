fn emit_invariant(out: &mut String, universe: &Universe, table: &RouteTable) {
    // A method is wire-invariant when it is direct in every enabled profile and
    // its result type agrees across those profiles.
    let canonical = universe.canonical();
    let mut invariant: Vec<u32> = Vec::new();
    for definition in &canonical.definitions {
        if definition.key.category != Category::Function {
            continue;
        }
        let mut ok = true;
        let mut first_result: Option<String> = None;
        for layer in &table.profiles {
            let Some(route) = table.lookup(*layer, definition.wire_id) else {
                ok = false;
                break;
            };
            if route.mode != RouteMode::Direct {
                ok = false;
                break;
            }
            let Some(other) = universe.schemas[layer].find_key(&definition.key) else {
                ok = false;
                break;
            };
            let rendered = other.result.as_string();
            match &first_result {
                None => first_result = Some(rendered),
                Some(expected) if expected != &rendered => {
                    ok = false;
                    break;
                }
                Some(_) => {}
            }
        }
        if ok {
            invariant.push(definition.wire_id);
        }
    }
    invariant.sort_unstable();
    invariant.dedup();
    out.push_str("/// Wire-invariant terminal methods, admissible without a profile.\nstatic INVARIANT_TERMINALS: &[u32] = &[");
    out.push_str(
        &invariant
            .iter()
            .map(|id| format!("{id:#010x}"))
            .collect::<Vec<_>>()
            .join(", "),
    );
    out.push_str("];\n\n");
    out.push_str(
        r#"/// Returns `true` when a terminal method is wire-invariant across profiles.
#[must_use]
pub fn is_invariant_terminal(wire_id: u32) -> bool {
    INVARIANT_TERMINALS.contains(&wire_id)
}

"#,
    );
}

/// Resolves the Rust field identifier of a named wrapper field.
fn wrapper_field(wrapper: &Definition, name: &str) -> Result<String, String> {
    wrapper
        .fields
        .iter()
        .find(|candidate| candidate.name == name)
        .map(|candidate| crate::emit::field_ident(&candidate.name))
        .ok_or_else(|| format!("wrapper {} has no field {name}", wrapper.key.qname))
}

fn emit_wrappers(out: &mut String, universe: &Universe) -> Result<(), String> {
    let canonical = universe.canonical();
    let wrappers: Vec<&Definition> = canonical
        .definitions
        .iter()
        .filter(|definition| {
            definition.key.category == Category::Function
                && definition.result.kind == TypeKind::GenericRef
        })
        .collect();
    out.push_str("/// Returns the inner query of a transparent wrapper, if any.\n");
    out.push_str("fn wrapper_query(method: &Method) -> Option<&Method> {\n    match method {\n");
    for wrapper in &wrappers {
        let ident = ident_for_qname(&wrapper.key.qname);
        let query = wrapper
            .fields
            .iter()
            .find(|field| field.ty.kind == TypeKind::GenericRef)
            .ok_or_else(|| format!("wrapper {} has no generic query field", wrapper.key.qname))?;
        let field = crate::emit::field_ident(&query.name);
        out.push_str(&format!(
            "        Method::{ident}(value) => Some(value.{field}.as_ref()),\n"
        ));
    }
    out.push_str("        _ => None,\n    }\n}\n\n");
    out.push_str(
        r#"/// Returns the layer selected by an `invokeWithLayer` wrapper.
fn wrapper_layer(method: &Method) -> Option<i32> {
    match method {
"#,
    );
    for wrapper in &wrappers {
        if local_name(wrapper) == "invokeWithLayer" {
            let ident = ident_for_qname(&wrapper.key.qname);
            out.push_str(&format!(
                "        Method::{ident}(value) => Some(value.layer),\n"
            ));
        }
    }
    out.push_str("        _ => None,\n    }\n}\n\n");
    out.push_str("/// Builds immutable metadata for one transparent wrapper.\n");
    out.push_str(
        "fn wrapper_metadata(\n    method: &Method,\n    profile: Option<Profile>,\n    semantic: SemanticId,\n) -> Wrapper {\n    match method {\n",
    );
    for wrapper in &wrappers {
        let ident = ident_for_qname(&wrapper.key.qname);
        match local_name(wrapper).as_str() {
            "invokeWithLayer" => {
                out.push_str(&format!(
                    "        Method::{ident}(_) => Wrapper {{\n            profile,\n            semantic,\n            wire_id: method.type_id(),\n            kind: WrapperKind::Layer,\n            client: None,\n            ordering: OrderingKey::default(),\n        }},\n"
                ));
            }
            "initConnection" => {
                let api_id = wrapper_field(wrapper, "api_id")?;
                let device_model = wrapper_field(wrapper, "device_model")?;
                let system_version = wrapper_field(wrapper, "system_version")?;
                let app_version = wrapper_field(wrapper, "app_version")?;
                let system_lang_code = wrapper_field(wrapper, "system_lang_code")?;
                let lang_pack = wrapper_field(wrapper, "lang_pack")?;
                let lang_code = wrapper_field(wrapper, "lang_code")?;
                out.push_str(&format!(
                    "        Method::{ident}(value) => Wrapper {{\n            profile,\n            semantic,\n            wire_id: method.type_id(),\n            kind: WrapperKind::InitConnection,\n            client: Some(ClientInfo {{\n                api_id: value.{api_id},\n                device_model: value.{device_model}.clone(),\n                system_version: value.{system_version}.clone(),\n                app_version: value.{app_version}.clone(),\n                system_lang_code: value.{system_lang_code}.clone(),\n                lang_pack: value.{lang_pack}.clone(),\n                lang_code: value.{lang_code}.clone(),\n            }}),\n            ordering: OrderingKey::default(),\n        }},\n"
                ));
            }
            "invokeAfterMsg" => {
                let msg_id = wrapper_field(wrapper, "msg_id")?;
                out.push_str(&format!(
                    "        Method::{ident}(value) => Wrapper {{\n            profile,\n            semantic,\n            wire_id: method.type_id(),\n            kind: WrapperKind::InvokeAfterMsg,\n            client: None,\n            ordering: OrderingKey {{ msg_ids: vec![value.{msg_id}] }},\n        }},\n"
                ));
            }
            "invokeAfterMsgs" => {
                let msg_ids = wrapper_field(wrapper, "msg_ids")?;
                out.push_str(&format!(
                    "        Method::{ident}(value) => Wrapper {{\n            profile,\n            semantic,\n            wire_id: method.type_id(),\n            kind: WrapperKind::InvokeAfterMsgs,\n            client: None,\n            ordering: OrderingKey {{ msg_ids: value.{msg_ids}.clone() }},\n        }},\n"
                ));
            }
            _ => {}
        }
    }
    out.push_str(
        "        _ => Wrapper {\n            profile,\n            semantic,\n            wire_id: method.type_id(),\n            kind: WrapperKind::Other,\n            client: None,\n            ordering: OrderingKey::default(),\n        },\n    }\n}\n\n",
    );
    Ok(())
}

