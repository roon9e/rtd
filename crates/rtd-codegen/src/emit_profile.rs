#[derive(Debug, Clone, Copy, PartialEq, Eq)]
enum AdmitMode {
    Frozen,
    Default,
    Unprofiled,
}

fn admit_impl(
    mode: AdmitMode,
    caller: Option<Profile>,
    body: &[u8],
    limits: Limits,
) -> Result<Admission, AdmitError> {
    if body.len() > limits.max_wire_bytes {
        return Err(AdmitError::Limit {
            name: "max_wire_bytes",
            value: body.len(),
        });
    }
    let mut decoder = Decoder::new(body, limits.decode_limits());
    let decoded = match caller {
        Some(profile) if matches!(mode, AdmitMode::Frozen) && profile.is_supported() => {
            decode_method_profile(profile, &mut decoder)?
        }
        _ => Method::decode(&mut decoder)?,
    };
    if !decoder.is_empty() {
        return Err(AdmitError::Limit {
            name: "trailing_bytes",
            value: decoder.remaining(),
        });
    }

    let mut explicit: Option<i32> = None;
    let mut wrappers: Vec<Wrapper> = Vec::new();
    let mut ordering: Vec<i64> = Vec::new();
    let mut wrapper_profile = match mode {
        AdmitMode::Unprofiled => None,
        AdmitMode::Frozen | AdmitMode::Default => caller,
    };
    let mut current: &Method = &decoded;
    while let Some(inner) = wrapper_query(current) {
        let wire_id = current.type_id();
        let semantic = semantic_for_wire_id(Profile::new(CANONICAL_LAYER), wire_id)
            .ok_or(AdmitError::UnsupportedTerminal(wire_id))?;
        let wrapper = wrapper_metadata(current, wrapper_profile, semantic);
        ordering.extend_from_slice(wrapper.ordering().as_slice());
        if let Some(layer) = wrapper_layer(current) {
            match explicit {
                None => explicit = Some(layer),
                Some(previous) if previous != layer => {
                    return Err(AdmitError::Conflict(previous, layer));
                }
                Some(_) => {}
            }
            wrapper_profile = Some(Profile::new(layer));
        }
        wrappers.push(wrapper);
        current = inner;
    }
    let terminal = current;
    let terminal_id = terminal.type_id();

    let effective = match mode {
        AdmitMode::Frozen => {
            let caller = caller.expect("frozen admission requires a profile");
            if let Some(layer) = explicit
                && layer != caller.layer
            {
                return Err(AdmitError::Conflict(caller.layer, layer));
            }
            Some(caller)
        }
        AdmitMode::Default => match explicit {
            Some(layer) => Some(Profile::new(layer)),
            None => caller,
        },
        AdmitMode::Unprofiled => explicit.map(Profile::new),
    };

    let mut admitted_profile: Option<Profile> = None;
    let mut admitted_wire_id = terminal_id;
    let semantic;
    if let Some(profile) = effective {
        if !profile.is_supported() {
            return Err(AdmitError::UnsupportedLayer(profile.layer));
        }
        // The terminal is canonical after decoding, so resolve its route by
        // semantic identity, which is stable across layers.
        let canonical_semantic = semantic_for_wire_id(Profile::new(CANONICAL_LAYER), terminal_id)
            .ok_or(AdmitError::UnsupportedTerminal(terminal_id))?;
        let route = lookup_route_semantic(profile, canonical_semantic)
            .ok_or(AdmitError::UnsupportedTerminal(terminal_id))?;
        if !matches!(route.mode, RouteMode::Direct | RouteMode::Retag) {
            return Err(AdmitError::UnsupportedRoute(route));
        }
        admitted_profile = Some(profile);
        admitted_wire_id = route.wire_id;
        semantic = canonical_semantic;
    } else {
        if !is_invariant_terminal(terminal_id) {
            return Err(AdmitError::RequiresProfile(terminal_id));
        }
        semantic = semantic_for_invariant(terminal_id)
            .ok_or(AdmitError::UnsupportedTerminal(terminal_id))?;
    }

    let call_identity = CallIdentity {
        semantic,
        wire_id: admitted_wire_id,
        ordering: OrderingKey { msg_ids: ordering },
    };
    let mut wire_digest = [0u8; 32];
    wire_digest.copy_from_slice(&sha256(body));
    Ok(Admission {
        effective_profile: admitted_profile,
        explicit_profile: explicit.map(Profile::new),
        wire_id: admitted_wire_id,
        semantic,
        request: decoded,
        wire_size: body.len(),
        wire_digest,
        wrappers,
        call_identity,
    })
}

/// Finds the semantic identity of a wire-invariant terminal.
fn semantic_for_invariant(wire_id: u32) -> Option<SemanticId> {
    for layer in PROFILES {
        if let Some(semantic) = ROUTES
            .iter()
            .find(|route| route.profile == *layer && route.wire_id == wire_id)
            .map(|route| route.semantic)
        {
            return Some(semantic);
        }
    }
    None
}

